const FK = [0xa3b1bac6, 0x56aa3350, 0x677d9197, 0xb27022dc]

const BLOCK = 16

/** 站点的 ROTL：右移那一半用有符号右移，这是和标准 SM4 唯一的不同。 */
function rotl(x, n) {
  return (x << n) | (x >> (32 - n))
}

function getUint32BE(bytes, i) {
  return ((bytes[i] & 255) << 24) | ((bytes[i + 1] & 255) << 16) | ((bytes[i + 2] & 255) << 8) | (bytes[i + 3] & 255)
}

function putUint32BE(n, out) {
  out.push((n >> 24) & 255, (n >> 16) & 255, (n >> 8) & 255, n & 255)
}

/** 非线性变换 τ：每个字节过一遍 S 盒。 */
function tau(x) {
  return (SBOX[(x >> 24) & 255] << 24) | (SBOX[(x >> 16) & 255] << 16) | (SBOX[(x >> 8) & 255] << 8) | SBOX[x & 255]
}

/** 加密轮里的线性变换 L。 */
function lt(x) {
  const b = tau(x)
  return b ^ rotl(b, 2) ^ rotl(b, 10) ^ rotl(b, 18) ^ rotl(b, 24)
}

/** 密钥扩展里的线性变换 L'。 */
function ltKey(x) {
  const b = tau(x)
  return b ^ rotl(b, 13) ^ rotl(b, 23)
}

function roundKeys(keyBytes) {
  const k = [0, 4, 8, 12].map((i, j) => getUint32BE(keyBytes, i) ^ FK[j])
  const keys = []
  for (let i = 0; i < 32; i++) {
    k[i + 4] = k[i] ^ ltKey(k[i + 1] ^ k[i + 2] ^ k[i + 3] ^ CK[i])
    keys.push(k[i + 4])
  }
  return keys
}

function cryptBlock(keys, bytes, offset, out) {
  const x = [0, 4, 8, 12].map((i) => getUint32BE(bytes, offset + i))
  for (let i = 0; i < 32; i++) {
    x[i + 4] = x[i] ^ lt(x[i + 1] ^ x[i + 2] ^ x[i + 3] ^ keys[i])
  }
  putUint32BE(x[35], out)
  putUint32BE(x[34], out)
  putUint32BE(x[33], out)
  putUint32BE(x[32], out)
}

function keyBytes(key) {
  const bytes = Buffer.from(String(key ?? ''), 'utf8')
  if (bytes.length !== BLOCK) throw new Error(`SM4 密钥要 16 字节，拿到的是 ${bytes.length} 字节`)
  return bytes
}

/**
 * 加密。plainText 不是字符串时先 JSON.stringify，和站点一样。
 * 返回站点格式的 Base64：'+' → '@'，'\r' → '#'，'\n' → '!'。
 */
export function encrypt(plainText, key) {
  const keys = roundKeys(keyBytes(key))
  const text = typeof plainText === 'string' ? plainText : JSON.stringify(plainText)
  const plain = Buffer.from(text, 'utf8')
  const pad = BLOCK - (plain.length % BLOCK)
  const padded = Buffer.concat([plain, Buffer.alloc(pad, pad)])
  const out = []
  for (let i = 0; i < padded.length; i += BLOCK) cryptBlock(keys, padded, i, out)
  return Buffer.from(out).toString('base64').replace(/\+/g, '@').replace(/\r/g, '#').replace(/\n/g, '!')
}

/**
 * 解密站点格式的密文，返回 UTF-8 字符串。
 * 和站点一样不校验填充：密钥不对时解出来是乱码，由调用方解析 JSON 时发现。
 * 密文不是 Base64、长度不是 16 的倍数时抛错。
 */
export function decrypt(cipherText, key) {
  const keys = roundKeys(keyBytes(key)).reverse()
  const text = String(cipherText ?? '').replace(/@/g, '+').replace(/#/g, '\r').replace(/!/g, '\n')
  // 站点用 atob 解码，它会跳过空白，所以 '#'、'!' 换回的换行在这里去掉
  const base64 = text.replace(/[\t\n\f\r ]/g, '')
  if (!/^[A-Za-z0-9+/]*={0,2}$/.test(base64) || base64.length % 4 === 1) throw new Error('SM4 密文不是 Base64')
  const raw = Buffer.from(base64, 'base64')
  if (raw.length === 0) return ''
  if (raw.length % BLOCK !== 0) throw new Error(`SM4 密文长度 ${raw.length} 不是 16 的倍数`)
  const out = []
  for (let i = 0; i < raw.length; i += BLOCK) cryptBlock(keys, raw, i, out)
  // 站点按有符号字节读填充长度，再照 Array.prototype.slice 的规则截掉
  const last = out[out.length - 1]
  const pad = last > 127 ? last - 256 : last
  const plain = Uint8Array.from(out).slice(0, out.length - pad)
  return new TextDecoder('utf-8').decode(plain)
}
